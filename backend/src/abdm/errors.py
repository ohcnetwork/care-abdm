"""
One failure shape for every ABDM failure (ADR-012).

`/docs/hiecm/v3/getting-started/build-it-well` says 2 things that shape this module:
  - "Every code in the error code reference carries an action. Key your handling to that column
    rather than to a list of codes you maintain by hand." -> `error_catalogue.ERROR_ACTIONS`,
    generated by `scripts/generate-error-catalogue.py`.
  - "A code on its own is not an error message. Say what failed and what the person can do next."
    -> every `Failure` carries 2 plain sentences.

`classify()` covers a refusal with a code, a refusal without one, an HTTP 5xx, a timeout, a
network error, an error block on a callback, and an answer that never came.

Pure module: no Django import, so `backend/tests` can import it. The desk sentences never say
gateway, callback, care context, HRP, bridge, token or probe (ADR-011).
"""

import re
from dataclasses import dataclass
from datetime import datetime, timedelta

from abdm.error_catalogue import ERROR_ACTIONS

# --- actions -----------------------------------------------------------------------------
# The first 10 are the docs' "What to do" column. The last 3 are the plug's own.

FIX_REQUEST = "fix_request"
FIX_AUTH = "fix_auth"
NEW_REQUEST_ID = "new_request_id"
NEW_CONSENT = "new_consent"
RETRY = "retry"
BACK_OFF = "back_off"
CANNOT_PROCEED = "cannot_proceed"
ASK_SUPPORT = "ask_support"
TREAT_AS_SUCCESS = "treat_as_success"
CHASE_HIP = "chase_hip"
BLOCKED = "blocked"
WAIT = "wait"
UNCLASSIFIED = "unclassified"

# --- retry kinds -------------------------------------------------------------------------

NOW = "now"  # safe to send again at once; the task retries with backoff
AFTER = "after"  # safe to send again only after `retry_after_seconds`
NEVER = "never"  # a repeat cannot help

# --- waits -------------------------------------------------------------------------------

# ABDM-1092. The gateway refuses a second link-token request for the same ABHA address at the
# same HIP inside this window. Observed 2026-09-17: refused up to 362 s, accepted from 374 s
# (findings F6, ADR-012). 7 minutes is the accepted figure plus margin.
TOKEN_REQUEST_WINDOW = timedelta(minutes=7)
# ABDM-1027 names the wait itself: "Please try again after 24 hours."
BLOCK_WAIT = timedelta(hours=24)
# ABDM-1022 "Too many requests". The threshold is not published (`concepts/gateway`), so back off.
BACK_OFF_WAIT = timedelta(minutes=1)
# An answer that never comes. Observed latency 1.9 s (E12); observed delivery retry 16 minutes
# (ADR-012). After this the plug reports "ABDM did not answer".
CALLBACK_DEADLINE = timedelta(minutes=10)

SUPPORT_LINE = "Give this reference to support: {reference}."
ADMIN_LINE = "Tell the administrator."


@dataclass(frozen=True)
class Failure:
    """What happened, what to do, and whether a repeat can help."""

    code: str = ""
    action: str = UNCLASSIFIED
    retry: str = NEVER
    retry_after_seconds: int = 0
    retry_at: datetime | None = None
    what: str = ""
    next_step: str = ""
    detail: str = ""
    support_reference: str = ""
    # The link call says the patient permission is wrong: drop it and ask for a new one.
    renew_permission: bool = False

    @property
    def succeeded(self) -> bool:
        return self.action == TREAT_AS_SUCCESS

    @property
    def retry_now(self) -> bool:
        return self.retry == NOW

    def as_dict(self) -> dict:
        """The `failure` block the state endpoint carries. The desk reads `what` and `nextStep`.
        `detail` holds ABDM's own words and `code` holds the code; both are for /admin/abdm."""
        return {
            "code": self.code,
            "action": self.action,
            "retry": self.retry,
            "retryAt": self.retry_at,
            "what": self.what,
            "nextStep": self.next_step,
            "detail": self.detail,
            "supportReference": self.support_reference,
        }

    def summary(self) -> str:
        """1 line for a log, an admin table or a stored `error_message`."""
        parts = [self.what, self.next_step]
        if self.detail and self.detail != self.what:
            parts.append(f"ABDM said: {self.detail}")
        if self.support_reference:
            parts.append(f"REQUEST-ID {self.support_reference}")
        return " ".join(part for part in parts if part)


@dataclass(frozen=True)
class _Rule:
    action: str
    what: str = ""
    next_step: str = ""
    wait: timedelta | None = None
    renew_permission: bool = False


