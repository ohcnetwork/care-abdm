# --- HTTP and transport, for a failure that carries no ABDM code ---------------------------

# Observed 2026-09-17: `m2-hip-link-care-context` answers HTTP 400 with an empty body and no code
# (findings E11). A repeat cannot help, so the desk gets the reference instead (ADR-012).
HTTP_ACTIONS: tuple[tuple[int, int, str], ...] = (
    (500, 599, RETRY),
    (429, 429, BACK_OFF),
    (401, 403, FIX_AUTH),
    (404, 404, FIX_REQUEST),
    (400, 428, ASK_SUPPORT),
)


def normalize_code(value) -> str:
    """`"ABDM-1027: "` -> `"ABDM-1027"`. The docs warn that codes arrive with trailing punctuation;
    observed 2026-09-17 on an error callback. Compare codes only through this function."""
    code = str(value or "").strip().rstrip(":").strip()
    prefix, sep, rest = code.partition("-")
    return f"{prefix.upper()}{sep}{rest}" if sep else code


def action_for(code: str) -> str:
    """The action ABDM asks for, after the sandbox overrides."""
    return _rule_for(normalize_code(code), None, "").action


def _http_action(http_status: int | None) -> str:
    for low, high, action in HTTP_ACTIONS:
        if http_status is not None and low <= http_status <= high:
            return action
    return UNCLASSIFIED


# The docs give some entries as a group ("HIS-1xxx") or a range ("HIS-400 to HIS-504") instead of 1
# code. A code that is not listed by itself falls back to its group, then to its range.
_GROUP_RE = re.compile(r"^([A-Z]+-)(\d)\d{3}$")
_HTTP_CODE_RE = re.compile(r"^HTTP_(\d{3})$")
_RANGE_RE = re.compile(r"^([A-Z]+-)(\d+) to \1(\d+)$")
_RANGES = [
    (match.group(1), int(match.group(2)), int(match.group(3)), action)
    for key, action in ERROR_ACTIONS.items()
    if (match := _RANGE_RE.match(key))
]


def _catalogue_action(code: str) -> str:
    if code in ERROR_ACTIONS:
        return ERROR_ACTIONS[code]
    group = _GROUP_RE.match(code)
    if group and f"{group.group(1)}{group.group(2)}xxx" in ERROR_ACTIONS:
        return ERROR_ACTIONS[f"{group.group(1)}{group.group(2)}xxx"]
    prefix, _, number = code.partition("-")
    if number.isdigit():
        for range_prefix, low, high, action in _RANGES:
            if range_prefix == f"{prefix}-" and low <= int(number) <= high:
                return action
    return ""


def _rule_for(code: str, http_status: int | None, exception: str) -> _Rule:
    if code in OVERRIDES:
        return OVERRIDES[code]
    if code in PLUG_CODES:
        return PLUG_CODES[code]
    action = _catalogue_action(code)
    if action:
        return _Rule(action, renew_permission=code in RENEW_PERMISSION_CODES)
    if exception:
        # A timeout or a broken connection. Nothing reached ABDM, so a repeat is safe.
        return _Rule(RETRY, "The plug could not reach ABDM.", "Try again in a few minutes.")
    return _Rule(_http_action(http_status))


def classify(
    *,
    code: str = "",
    http_status: int | None = None,
    message: str = "",
    exception: str = "",
    request_id: str = "",
    since: datetime | None = None,
) -> Failure:
    """Turn 1 failure into the shape the desk, the task and the admin page all read.

    `code`        the ABDM code, a plug code, or empty.
    `http_status` the HTTP status of the answer, when there was one.
    `message`     the message ABDM sent. It is kept as `detail` for the admin page. The desk
                  always reads the plug's own sentence, which carries no ABDM jargon (ADR-011).
    `exception`   the class name of a transport failure, for example `ConnectTimeout`.
    `request_id`  the REQUEST-ID, which is the reference support asks for.
    `since`       the time the wait runs from. For `ABDM-1092` that is when the **accepted**
                  request went out, because the window runs from that one, not from the refusal.
    """
    code = normalize_code(code)
    if http_status is None:
        # `outbound.send()` stores `HTTP_400` when ABDM refuses with no code of its own. Read the
        # status back out of it, so a stored `HTTP_503` is repeated and a stored `HTTP_400` is not.
        stored = _HTTP_CODE_RE.match(code)
        if stored:
            http_status = int(stored.group(1))
    rule = _rule_for(code, http_status, exception)
    action = rule.action
    what, next_step = ADVICE.get(action, ADVICE[UNCLASSIFIED])
    if code in MESSAGES:
        what, next_step = MESSAGES[code]
    if rule.what:
        what = rule.what
    if rule.next_step:
        next_step = rule.next_step
    next_step = next_step.replace("{reference}", request_id or "none")
    if not request_id and next_step.endswith("support: none."):
        next_step = ADMIN_LINE
    retry = RETRY_KIND.get(action, NEVER)
    wait = rule.wait or DEFAULT_WAIT.get(action)
    seconds = int(wait.total_seconds()) if wait else 0
    retry_at = since + wait if (retry == AFTER and wait and since) else None
    return Failure(
        code=code,
        action=action,
        retry=retry,
        retry_after_seconds=seconds,
        retry_at=retry_at,
        what=what,
        next_step=next_step,
        detail=message.strip(),
        support_reference=request_id,
        renew_permission=rule.renew_permission or code in RENEW_PERMISSION_CODES,
    )


def no_answer(request_id: str = "", since: datetime | None = None) -> Failure:
    """A request ABDM accepted and never answered (ADR-012 D6)."""
    return classify(code="NO_ANSWER", request_id=request_id, since=since)


def answer_overdue(sent_at: datetime | None, now: datetime) -> bool:
    """True when an accepted request has waited longer than the plug is prepared to wait."""
    return bool(sent_at) and (now - sent_at) > CALLBACK_DEADLINE


def window_open(sent_at: datetime | None, now: datetime) -> bool:
    """True while a second link-token request for the same patient would be refused (F6)."""
    return bool(sent_at) and (now - sent_at) < TOKEN_REQUEST_WINDOW


def window_ends(sent_at: datetime) -> datetime:
    return sent_at + TOKEN_REQUEST_WINDOW
